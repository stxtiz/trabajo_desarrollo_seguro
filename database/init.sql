-- 8. Tabla: sesiones (Gestión de sesiones en servidor - OWASP ASVS v5.0 V3 Nivel 3)
CREATE TABLE sesiones (
    sid VARCHAR(128) PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
    nombre_usuario VARCHAR(255) DEFAULT NULL,
    restaurante_id INTEGER DEFAULT 1,
    csrf_token VARCHAR(128) NOT NULL,
    carrito JSONB NOT NULL DEFAULT '{}'::jsonb,
    ip_address VARCHAR(64) NOT NULL,
    user_agent VARCHAR(512) DEFAULT NULL,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultima_actividad TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_en TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_sesiones_expira ON sesiones(expira_en);
CREATE INDEX idx_sesiones_usuario ON sesiones(usuario_id);

-- 9. Tabla: auditoria_seguridad (Trazabilidad de eventos de seguridad - OWASP ASVS v5.0 V7 Nivel 3)
CREATE TABLE auditoria_seguridad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento VARCHAR(100) NOT NULL,
    severidad VARCHAR(20) NOT NULL DEFAULT 'INFO',
    usuario_id INTEGER DEFAULT NULL,
    ip_address VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    detalles JSONB DEFAULT '{}'::jsonb,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_evento ON auditoria_seguridad(evento, creado_en DESC);
CREATE INDEX idx_comentarios_restaurante ON comentarios(id_restaurante);
CREATE INDEX idx_cartas_restaurante ON cartas(restaurantes_id);
